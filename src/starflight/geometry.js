function ship(width, size, solidBounds, muzzles, engines, body) {
  const height = width * size[1] / size[0];
  return { width, height, display: [width, height], pivot: [.5, .5], solidBounds, muzzles, engines,
    body: body.map(([u, v, radius]) => ({ uv: [u, v], r: radius * width })) };
}
