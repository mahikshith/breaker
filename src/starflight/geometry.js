export const PLAYER_EDGE = SHIPS.player.width * .52;

export function shipPoint(kind, x, y, angle, uv) {
  const s = SHIPS[kind], dx = (uv[0] - s.pivot[0]) * s.width, dy = (uv[1] - s.pivot[1]) * s.height;
  const c = Math.cos(angle), sn = Math.sin(angle);
  return { x: x + dx * c - dy * sn, y: y + dx * sn + dy * c };
}

export function shipCircles(kind, x, y, angle = 0) {
  return SHIPS[kind].body.map(c => ({ ...shipPoint(kind, x, y, angle, c.uv), r: c.r }));
}
