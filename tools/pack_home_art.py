"""Pack the store key art as the home-screen hero: src/home-art.js (a WebP data URL plus its size).

store/key-art.png has a 1-2 px light edge at the bottom; it is cropped off, then the art is resized to 1100 px wide.
Run: python3 tools/pack_home_art.py
"""
import base64, io, pathlib
from PIL import Image

root = pathlib.Path(__file__).resolve().parent.parent
im = Image.open(root / 'store' / 'key-art.png').convert('RGB')
im = im.crop((0, 0, im.width, 576))
w = 1100
im = im.resize((w, round(im.height * w / im.width)), Image.LANCZOS)
buf = io.BytesIO()
im.save(buf, 'WEBP', quality=88, method=6)
url = 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()
(root / 'src' / 'home-art.js').write_text(
    '// Generated by tools/pack_home_art.py from store/key-art.png. Do not edit by hand.\n'
    f'export const HOME_ART = {{ url: "{url}", w: {im.width}, h: {im.height}, kit: [0.43, 0.62], lumi: [0.89, 0.2], ball: [0.61, 0.39] }};\n')
print(im.size, len(buf.getvalue()) // 1024, 'KB')
