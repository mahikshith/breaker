"""Pack the round-3 M365 character frames (assets/round3/<who>/, cut by art/round3/cut.py) into src/round3-art.js.
Kept apart from src/vault-art.js so the character art repacks in seconds and never conflicts with the big pack.
Frames ship as lossy WebP (alpha stays lossless). Run: python3 tools/pack_round3.py
"""
import base64, io, json, os
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = {}
for who in ('nerra', 'warden'):
    d = os.path.join(ROOT, 'assets', 'round3', who)
    if not os.path.isdir(d): continue
    out[who] = {}
    for key, f in json.load(open(os.path.join(d, 'manifest.json')))['frames'].items():
        with Image.open(os.path.join(d, f['file'])) as im:
            b = io.BytesIO(); im.save(b, 'WEBP', quality=85, method=6)
            out[who][key] = {'url': 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode(), 'w': im.width, 'h': im.height}
js = '// Round-3 character frames, generated by tools/pack_round3.py from assets/round3/. Do not edit by hand.\nexport const R3 = ' + json.dumps(out) + ';\n'
open(os.path.join(ROOT, 'src', 'round3-art.js'), 'w').write(js)
print(f'src/round3-art.js: {len(js) / 1024:.0f} KB', {k: len(v) for k, v in out.items()})
