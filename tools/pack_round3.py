"""Pack the round-3 M365 art (assets/round3/<set>/, cut by art/round3/cut.py and cut_drop2.py) into src/round3-art.js.
Kept apart from src/vault-art.js so this art repacks in seconds and never conflicts with the big pack.
Sprites ship as lossy WebP (alpha stays lossless), lightly sharpened at source size: the M365 frames are small and the
game draws them about 3x on a phone, where a little unsharp mask keeps the eyes and edges from going soft.
Each set has a longest-side cap so the bundle stays inside its budget. Run: python3 tools/pack_round3.py
"""
import base64, io, json, os
from PIL import Image, ImageFilter
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# set: (longest side cap in px, sharpen, only these frames or None for all)
SETS = {
    'nerra': (None, True, None),
    'warden': (300, True, None),
    'korr': (220, True, None),
    'bricks': (150, False, None),
    'fx': (180, False, None),
    'tidewheel-parts': (200, False, None),
}
out, kb = {}, {}
for name, (cap, sharpen, only) in SETS.items():
    d = os.path.join(ROOT, 'assets', 'round3', name)
    if not os.path.isdir(d): continue
    out[name] = {}; size = 0
    for key, f in json.load(open(os.path.join(d, 'manifest.json')))['frames'].items():
        if only and key not in only: continue
        with Image.open(os.path.join(d, f['file'])) as src:
            im = src.convert('RGBA'); w, h = im.size   # w, h: source size, the unit the game's scale constants use
            if cap and max(im.size) > cap: im = im.resize((round(w * cap / max(w, h)), round(h * cap / max(w, h))), Image.LANCZOS)
            if sharpen:
                rgb = im.convert('RGB').filter(ImageFilter.UnsharpMask(1, 70, 2)); rgb.putalpha(im.getchannel('A')); im = rgb
            b = io.BytesIO(); im.save(b, 'WEBP', quality=85, method=6); size += b.tell()
            out[name][key] = {'url': 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode(), 'w': w, 'h': h}
    kb[name] = round(size * 4 / 3 / 1024)
js = '// Round-3 art, generated by tools/pack_round3.py from assets/round3/. Do not edit by hand.\nexport const R3 = ' + json.dumps(out) + ';\n'
open(os.path.join(ROOT, 'src', 'round3-art.js'), 'w').write(js)
print(f'src/round3-art.js: {len(js) / 1024:.0f} KB', kb)
